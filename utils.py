async def send_emails_concurrently(patient_email: str, patient_subject: str, patient_body: str, doctor_email: str, doctor_subject: str, doctor_body: str) -> bool:
    """Dispatches the patient and doctor emails concurrently using asyncio threads."""
    try:
        results = await asyncio.gather(
            asyncio.to_thread(send_email, patient_email, patient_subject, patient_body),
            asyncio.to_thread(send_email, doctor_email, doctor_subject, doctor_body),
            return_exceptions=True
        )
        # We can handle or log exceptions separately if required, but we return True if the patient email succeeded
        patient_sent = results[0]
        doctor_sent = results[1]
        
        if isinstance(doctor_sent, Exception):
            print(f"Doctor email thread exception: {doctor_sent}")
        
        if isinstance(patient_sent, Exception):
            print(f"Patient email thread exception: {patient_sent}")
            return False
            
        return patient_sent
    except Exception as e:
        print(f"Fatal error during concurrent email dispatch: {e}")
        return False
