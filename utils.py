SERVICE_ACCOUNT_FILE = os.path.join(os.path.dirname(__file__), 'service_account.json')
TOKEN_FILE = os.path.join(os.path.dirname(__file__), 'token.json')
CALENDAR_SCOPES = [
    'https://www.googleapis.com/auth/calendar',
    'https://www.googleapis.com/auth/gmail.send',
    'https://www.googleapis.com/auth/meetings.space.created',
]


def _get_calendar_service():
    """
    Returns a Google Calendar service using OAuth token if available,
    otherwise falls back to Service Account.
    """
    if os.path.exists(TOKEN_FILE):
        creds = Credentials.from_authorized_user_file(TOKEN_FILE, CALENDAR_SCOPES)
        return build('calendar', 'v3', credentials=creds)
    else:
        creds = service_account.Credentials.from_service_account_file(
            SERVICE_ACCOUNT_FILE, scopes=CALENDAR_SCOPES
        )
        return build('calendar', 'v3', credentials=creds)


def generate_meet_link(date_str: str, time_str: str, attendee_emails: list = None) -> str:
    """
    Creates a Google Calendar event with a Google Meet conference link.
    Requires token.json (generated by running auth_calendar.py once).
    Returns the Google Meet hangout link, or None if creation fails.

    The account whose token.json is used becomes the organizer (auto-joins
    as host with no waiting room). All other attendees get responseStatus
    'accepted' so Google Meet recognises them as confirmed invited guests.
    The organizer email is excluded from attendees to avoid a self-invite.
    """
    try:
        service = _get_calendar_service()

        dt_str = f"{date_str} {time_str}"
        dt = datetime.datetime.strptime(dt_str, "%Y-%m-%d %I:%M %p")
        start_time = dt.isoformat()
        end_time = (dt + datetime.timedelta(hours=1)).isoformat()

        # Exclude the organizer (token.json account) from attendees
        # to avoid a redundant self-invite.
        organizer_email = os.getenv("GMAIL_USER", "").lower()
        filtered_emails = [
            e for e in (attendee_emails or [])
            if e.lower() != organizer_email
        ]

        # responseStatus='accepted' marks guests as confirmed invitees,
        # which is the best signal we can send via the Calendar API.
        attendees = [
            {'email': e, 'responseStatus': 'accepted'}
            for e in filtered_emails
        ]

        event = {
            'summary': 'Rehab 5 Consultation',
            'location': 'Online - Google Meet',
            'description': 'Your scheduled consultation with Rehab 5.',
            'start': {'dateTime': start_time, 'timeZone': 'Asia/Dubai'},
            'end': {'dateTime': end_time, 'timeZone': 'Asia/Dubai'},
            'conferenceData': {
                'createRequest': {
                    'requestId': uuid.uuid4().hex,
                    'conferenceSolutionKey': {'type': 'hangoutsMeet'}
                }
            },
            'attendees': attendees,
            'guestsCanModify': True,
            'guestsCanInviteOthers': True,
            'guestsCanSeeOtherGuests': True,
            'visibility': 'public',
            'anyoneCanAddSelf': True,
            'status': 'confirmed',
        }

        event_result = service.events().insert(
            calendarId='primary',
            body=event,
            conferenceDataVersion=1,
            sendUpdates='all'   # sends Google Calendar invite emails
        ).execute()

        meet_link = event_result.get('hangoutLink')

        # Attempt to disable host management on the newly created space
        # via the Meet REST API so no one is stuck in a waiting room.
        if meet_link:
            try:
                _disable_host_management(meet_link)
            except Exception as meet_err:
                print(f"[Meet API] Could not disable host management (non-fatal): {meet_err}")

        return meet_link

    except Exception as e:
        print(f"Google Meet event creation failed: {e}")
        return None


def _disable_host_management(meet_link: str):
    """
    Uses the Google Meet REST API to set the space access to OPEN
    so no participant ever sees 'waiting for host to admit you'.
    meet_link example: https://meet.google.com/abc-defg-hij
    """
    import json as _json
    import urllib.request as urlreq

    # Extract the meeting code from the link
    code = meet_link.rstrip('/').split('/')[-1]  # e.g. 'abc-defg-hij'

    creds = Credentials.from_authorized_user_file(TOKEN_FILE, CALENDAR_SCOPES)
    if creds.expired and creds.refresh_token:
        from google.auth.transport.requests import Request
        creds.refresh(Request())

    # PATCH the space to set access type to OPEN (no waiting room)
    url = f"https://meet.googleapis.com/v2/spaces/{code}"
    payload = _json.dumps({
        "config": {
            "accessType": "OPEN",
            "entryPointAccess": "ALL"
        }
    }).encode()

    req = urlreq.Request(
        url,
        data=payload,
        method='PATCH',
        headers={
            'Authorization': f'Bearer {creds.token}',
            'Content-Type': 'application/json',
            'X-Goog-FieldMask': 'config.accessType,config.entryPointAccess'
        }
    )
    with urlreq.urlopen(req) as resp:
        result = _json.loads(resp.read())
        print(f"[Meet API] Space updated: accessType={result.get('config', {}).get('accessType')}")
        return False


def create_calendar_event(date_str: str, time_str: str, meet_link: str) -> bool:
    """
    Creates a plain Google Calendar event with the meet_link in the description.
    Used as fallback.
    """
    try:
        service = _get_calendar_service()

        dt_str = f"{date_str} {time_str}"
        dt = datetime.datetime.strptime(dt_str, "%Y-%m-%d %I:%M %p")
        start_time = dt.isoformat()
        end_time = (dt + datetime.timedelta(hours=1)).isoformat()

        event = {
            'summary': 'Rehab 5 Consultation',
            'location': meet_link,
            'description': f'Join the consultation: {meet_link}',
            'start': {'dateTime': start_time, 'timeZone': 'Asia/Dubai'},
            'end': {'dateTime': end_time, 'timeZone': 'Asia/Dubai'},
        }

        service.events().insert(calendarId='primary', body=event).execute()
        return True

    except Exception as e:
        print(f"Calendar event creation failed: {e}")
        return False


def send_email(to_email: str, subject: str, body: str) -> bool:
    """
    Sends an email via the Gmail API (HTTPS) instead of SMTP.
    Uses the existing token.json OAuth credentials.
    """
    sender_email = os.getenv("GMAIL_USER")
    if not sender_email:
        print("GMAIL_USER not found in env")
        return False

    try:
        creds = Credentials.from_authorized_user_file(TOKEN_FILE, CALENDAR_SCOPES)
        service = build('gmail', 'v1', credentials=creds)

        msg = MIMEMultipart("alternative")
        msg['From'] = f"Rehab 5 <{sender_email}>"
        msg['To'] = to_email
        msg['Reply-To'] = sender_email
        msg['Subject'] = subject
        msg.attach(MIMEText(body, 'html'))

        raw = base64.urlsafe_b64encode(msg.as_bytes()).decode()
        service.users().messages().send(
            userId='me',
            body={'raw': raw}
        ).execute()

        print(f"Email sent successfully to {to_email}")
        return True
    except Exception as e:
        print(f"Email failed: {e}")
        return False

